import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createIsolatedDevelopmentDatabase,identities as i,actor,administrator} from './fixtures/isolated-development-database.mjs';

test('household comments follow the current source grant without changing the original',async t=>{
 const db=await createIsolatedDevelopmentDatabase();
 t.after(()=>db.close());
 await db.exec(await readFile(new URL('../supabase/drafts/private_household_comments.sql',import.meta.url),'utf8'));
 const records=(await db.query('select id,version,payload from public.cc_records')).rows;
 const source=label=>records.find(row=>row.payload.label===label);
 const comments=async()=>(await db.query('select source_id,author_id,body from public.cc_household_comments order by body')).rows;
 const add=(label,body)=>db.query('insert into public.cc_household_comments (source_id,body) values ($1,$2)',[source(label).id,body]);
 await actor(db,i.a,i.sa);
 await add('shared-home','Fictional household comment');
 await assert.rejects(add('private-a','Private source'),/row-level security/);
 await actor(db,i.b,i.sb);
 assert.deepEqual(await comments(),[{source_id:source('shared-home').id,author_id:i.a,body:'Fictional household comment'}]);
 await assert.rejects(add('shared-home','Read-only member'),/row-level security/);
 await assert.rejects(add('other-home','Other household source'),/row-level security/);
 await add('shared-school','Fictional school comment');
 await assert.rejects(db.query('update public.cc_household_comments set body=$1',['Edited']),/permission denied/);
 await actor(db,i.c,i.sc);
 assert.deepEqual(await comments(),[]);
 await administrator(db);
 await db.query("update public.cc_household_memberships set read_sections='{}',write_sections='{}' where user_id=$1",[i.b]);
 await actor(db,i.b,i.sb);
 assert.deepEqual(await comments(),[]);
 await administrator(db);
 const current=(await db.query('select id,version,payload from public.cc_records')).rows;
 assert.deepEqual(current,records);
 await db.query('update public.cc_records set deleted_at=now() where id=$1',[source('shared-home').id]);
 await actor(db,i.a,i.sa);
 assert.deepEqual((await comments()).map(row=>row.body),['Fictional school comment']);
 await administrator(db);
 await db.exec('set role anon');
 await assert.rejects(comments(),/permission denied/);
 await administrator(db);
 const inverse=await readFile(new URL('../supabase/drafts/private_household_comments_rollback.sql',import.meta.url),'utf8');
 await assert.rejects(db.exec(inverse),/while comments are retained/);
 await db.exec('rollback');
 assert.equal((await comments()).length,2);
});
