import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
import {createIsolatedDevelopmentDatabase,identities as i,actor,administrator} from './fixtures/isolated-development-database.mjs';

test('an approved redemption deducts points once and retains its original approver',async t=>{
 const db=await createIsolatedDevelopmentDatabase();
 t.after(()=>db.close());
 const sql=name=>readFile(new URL('../supabase/drafts/'+name+'.sql',import.meta.url),'utf8');
 await db.exec(await sql('private_household_approver'));
 await db.exec(await sql('private_household_redemption'));
 const [account,first,second]=Array.from({length:3},()=>randomUUID());
 await db.query('insert into cc_private.household_point_accounts values($1,$2,10)',[i.home,account]);
 await db.query('insert into cc_private.household_redemptions(household_id,id,account_id,cost) values($1,$2,$4,7),($1,$3,$4,7)',[i.home,first,second,account]);
 await db.query('insert into cc_private.household_approvers values($1,$2)',[i.home,i.b]);
 const approve=async (home,id)=>(await db.query('select public.cc_approve_household_redemption($1,$2) as approved',[home,id])).rows[0].approved;
 await actor(db,i.a,i.sa);
 assert.equal(await approve(i.home,first),false);
 await actor(db,i.b,i.sb);
 assert.equal(await approve(i.other,first),false);
 assert.equal(await approve(i.home,first),true);
 assert.equal(await approve(i.home,first),true);
 assert.equal(await approve(i.home,second),false);
 await assert.rejects(db.query('select balance from cc_private.household_point_accounts'),/permission denied/);
 await administrator(db);
 assert.equal((await db.query('select balance from cc_private.household_point_accounts')).rows[0].balance,3);
 const results=(await db.query('select id,approved_by,approved_at from cc_private.household_redemptions')).rows;
 assert.equal(results.find(row=>row.id===first).approved_by,i.b);
 assert.ok(results.find(row=>row.id===first).approved_at);
 assert.equal(results.find(row=>row.id===second).approved_at,null);
 await db.query("update public.cc_household_memberships set status='removed' where household_id=$1 and user_id=$2",[i.home,i.b]);
 await actor(db,i.b,i.sb);
 assert.equal(await approve(i.home,first),false);
 await administrator(db);
 await assert.rejects(db.exec(await sql('private_household_redemption_rollback')),/while balances or redemptions are retained/);
 await db.exec('rollback');
 assert.equal((await db.query('select balance from cc_private.household_point_accounts')).rows[0].balance,3);
});
